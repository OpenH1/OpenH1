#!/usr/bin/env python3
"""Build the Vulkan backend's ID buffer pass (the replay's, port/tools/replay).

Run with glslangValidator and spirv-val on PATH:
    python3 tools/vulkan_inspect_shader.py
The generated C (port/linux/vulkan/xgpu_vulkan_inspect_shader.c) embeds the
SPIR-V of the compute shader below; the backend needs no shader compiler for
it. --check verifies that the checked-in file still matches its source.

The replay asks for a frame's ID buffer: each pixel's draws that changed it,
topmost first (host_render_replay.h). Around each draw into the target the
frame presents, the backend copies the target before the draw (resolves it,
for a multisampled target's samples, and resolves it again after) and this
pass compares the two, texel by texel, by their bits: where they differ,
the draw's number goes on top of the pixel's stack (a layer of the ID
image each), the others down one, the last let go. A draw drawn in several
parts keeps one place in the stack.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "port/linux/vulkan/xgpu_vulkan_inspect_shader.c"

SOURCE = """#version 450
layout(local_size_x = 8, local_size_y = 8) in;
layout(set = 0, binding = 0) uniform sampler2D before_image;
layout(set = 0, binding = 1) uniform sampler2D after_image;
layout(set = 0, binding = 2, r32ui) uniform uimage2DArray ids;
layout(push_constant) uniform draw_block
{
	ivec4 area;
	uint number;
	uint depth;
} draw;

void main()
{
	ivec2 at = ivec2(gl_GlobalInvocationID.xy) + draw.area.xy;
	int layer;

	if (gl_GlobalInvocationID.x >= uint(draw.area.z) || gl_GlobalInvocationID.y >= uint(draw.area.w))
		return;
	if (floatBitsToUint(texelFetch(before_image, at, 0)) == floatBitsToUint(texelFetch(after_image, at, 0)))
		return;
	if (imageLoad(ids, ivec3(at, 0)).x == draw.number)
		return;
	for (layer = int(draw.depth) - 1; layer > 0; layer--)
		imageStore(ids, ivec3(at, layer), imageLoad(ids, ivec3(at, layer - 1)));
	imageStore(ids, ivec3(at, 0), uvec4(draw.number));
}
"""


def compile_source(compiler: str, validator: str) -> bytes:
    with tempfile.TemporaryDirectory() as folder:
        source = Path(folder) / "inspect.comp"
        output = Path(folder) / "inspect.spv"
        source.write_text(SOURCE, encoding="utf-8")
        subprocess.run([compiler, "-V", "--target-env", "vulkan1.1", "-o", str(output), str(source)], check=True,
                       stdout=subprocess.DEVNULL)
        subprocess.run([validator, "--target-env", "vulkan1.1", str(output)], check=True)
        return output.read_bytes()


def generate(code: bytes) -> str:
    words = struct.unpack(f"<{len(code) // 4}I", code)
    lines = []
    for start in range(0, len(words), 8):
        lines.append("\t" + " ".join(f"0x{word:08x}," for word in words[start:start + 8]))
    source = "\n".join(SOURCE.rstrip("\n").split("\n"))
    return (
        "/*\nXGPU_VULKAN_INSPECT_SHADER.C\n\n"
        "Generated by tools/vulkan_inspect_shader.py from the GLSL below: do not edit.\n"
        "The replay's ID buffer pass (xgpu_vulkan.c's xgpu_vulkan_inspect_*).\n\n"
        + source.replace("*/", "* /") + "\n*/\n\n"
        "#include <stddef.h>\n#include <stdint.h>\n\n"
        f"const uint32_t xgpu_vulkan_inspect_shader[{len(words)}] =\n{{\n" + "\n".join(lines) + "\n};\n"
        "const size_t xgpu_vulkan_inspect_shader_size = sizeof(xgpu_vulkan_inspect_shader);\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--compiler", default="glslangValidator")
    parser.add_argument("--validator", default="spirv-val")
    parser.add_argument("--check", action="store_true", help="fail if the checked-in file differs")
    arguments = parser.parse_args()
    text = generate(compile_source(arguments.compiler, arguments.validator))
    if arguments.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{OUTPUT} is not what tools/vulkan_inspect_shader.py makes: run it")
        return
    OUTPUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
