#!/usr/bin/env python3
"""Generate the guest image's host import stubs.

Every function the guest imports from the host (port/android/host_imports.list
and the others) gets a stub in the image that loads the host's 64-bit
function address from __host_import_table and branches to it.
The arguments are left untouched in their registers; the host fills in the
table when it loads the image (port/android/host/host_loader.c). The stub's
instructions are the guest architecture's (tools/guest_arch.py, import_stub).

Usage: android_imports.py --arch NAME [--base-register --prototypes header ...]
       [--host-table table.c] output.s list...

With --host-table, also writes the host's name-to-function table for the
names in the lists.

With --base-register, the guest's memory lies at a base in x21
(tools/guest_base_register.py), and each stub turns the pointer arguments
of its function into host addresses (base plus offset; NULL stays NULL)
before the branch. The --prototypes files (C declarations, such as
port/android/guest/runtime/guest_host.h) say which arguments are pointers.
The posix imports (hostposix_) are called from generated C wrappers that
translate their own. Only AArch64 has a base
register (tools/guest_arch.py, base_register_flags).

With --host-abi sysv (the 64-bit Windows host, port/windows/host), the
guest's calling convention (System V's, x32) is not the host's (Microsoft's
x64): the table's entries are then thunks the table's file defines, one for
each import, with clang's sysv_abi attribute, which take the guest's
arguments and call the host function with the host's convention. Each
import needs a prototype in the --prototypes files (posix.h for the
hostposix_ imports), from which the thunk takes its arguments' classes
(tools/check_host_imports.py: a pointer, a 32-bit or 64-bit integer, a
float or a double).
"""

import re
import sys

from guest_arch import GUEST_ARCHES
import check_host_imports

INTEGER_REGISTER_COUNT = 8
FLOAT_TYPES = ("float", "double")


def pointer_arguments(paths):
    """{name: [integer register numbers of its pointer arguments]} for the
    functions the files declare."""
    result = {}
    for path in paths:
        text = open(path, encoding="utf-8").read()
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        text = re.sub(r"//[^\n]*", "", text)
        for name, params in re.findall(r"\b(\w+)\s*\(([^;{}()]*)\)\s*(?:__attribute__\s*\(\([^;]*?\)\))?\s*;", text):
            params = " ".join(params.split())
            registers, integer = [], 0
            if params not in ("", "void"):
                for param in params.split(","):
                    param = param.strip()
                    if "*" in param:
                        if integer >= INTEGER_REGISTER_COUNT:
                            raise SystemExit(f"{name}: a pointer argument on the stack")
                        registers.append(integer)
                        integer += 1
                    elif re.match(r"^(const\s+)?(float|double)\b", param):
                        continue
                    else:
                        integer += 1
            result[name] = registers
    return result


# each argument or result class (tools/check_host_imports.py) as the thunks
# declare it: types the System V and Microsoft conventions both pass in the
# argument's own register (an integer or pointer register, or a vector
# register), so that the compiler moves each from the guest's place to the
# host's. A 32-bit integer is an int (its register's upper half is undefined
# in either convention), a guest pointer a void * (the guest zero-extends it).
THUNK_TYPES = {"pointer": "void *", "int32": "int", "int64": "long long", "float": "float", "double": "double",
               "void": "void"}


def host_symbol(name):
    """the host function of an import: hostposix_<name> imports
    port/linux/src/posix.h's posix_<name>"""
    return "posix_" + name[len("hostposix_"):] if name.startswith("hostposix_") else name


def thunk_prototypes(paths):
    """{name: (result class, [argument classes])} for the host_ and posix_
    functions the files declare; SystemExit on a type a thunk cannot pass"""
    result = {}
    for path in paths:
        text = open(path, encoding="utf-8").read()
        for prototype in check_host_imports.parse_prototypes(text, path):
            classes = prototype.classes()
            if "bad" in classes or prototype.result_class() == "bad":
                raise SystemExit(f"{prototype.where}: {prototype.name}: a type the thunks cannot pass "
                                 f"(tools/check_host_imports.py)")
            result.setdefault(prototype.name, (prototype.result_class(), classes))
    return result


def sysv_host_table(names, prototypes):
    """the Windows host's table (--host-abi sysv): a thunk for each import"""
    table = ["/* generated by tools/android_imports.py --host-abi sysv; do not edit */",
             "#include <string.h>", "",
             "/* the guest's calling convention, which its import stubs jump with */",
             "#define GUEST_ABI __attribute__((sysv_abi))", ""]
    entries = []
    for index, name in enumerate(names):
        symbol = host_symbol(name)
        if symbol not in prototypes:
            raise SystemExit(f"{name}: no prototype of {symbol} in the --prototypes files")
        result, classes = prototypes[symbol]
        parameters = ", ".join(f"{THUNK_TYPES[kind]} a{number}" for number, kind in enumerate(classes)) or "void"
        types = ", ".join(THUNK_TYPES[kind] for kind in classes) or "void"
        arguments = ", ".join(f"a{number}" for number in range(len(classes)))
        call = f"{symbol}({arguments})"
        table += [f"{THUNK_TYPES[result]} {symbol}({types});",
                  f"static GUEST_ABI {THUNK_TYPES[result]} import_{index}({parameters})",
                  "{",
                  f"\t{call};" if result == "void" else f"\treturn {call};",
                  "}", ""]
        entries.append(f'\t{{ "{name}", (void *)import_{index} }},')
    table += ["static const struct { const char *name; void *function; } imports[] =", "{", *entries, "};", ""]
    return table


def main():
    arguments = sys.argv[1:]
    if arguments[:1] != ["--arch"] or len(arguments) < 2 or arguments[1] not in GUEST_ARCHES:
        sys.exit(__doc__)
    arch = GUEST_ARCHES[arguments[1]]
    arguments = arguments[2:]
    host_table = None
    base_register = False
    host_abi = None
    prototype_files = []
    while arguments[0] in ("--base-register", "--prototypes", "--host-abi"):
        if arguments[0] == "--base-register":
            base_register = True
            arguments = arguments[1:]
        elif arguments[0] == "--host-abi":
            host_abi = arguments[1]
            arguments = arguments[2:]
        else:
            prototype_files.append(arguments[1])
            arguments = arguments[2:]
    if base_register and arch.base_register_flags is None:
        sys.exit(f"the {arch.name} guest has no base register")
    if host_abi not in (None, "sysv") or (host_abi and (base_register or arch.name != "x32")):
        sys.exit("--host-abi sysv is for the x32 guest without a base register (the Windows host)")
    pointers = pointer_arguments(prototype_files) if base_register else {}
    if arguments[0] == "--host-table":
        host_table = arguments[1]
        arguments = arguments[2:]
    output, lists = arguments[0], arguments[1:]
    names = []
    for path in lists:
        for line in open(path, encoding="utf-8"):
            line = line.split("#", 1)[0].strip()
            if line and line not in names:
                names.append(line)
    out = ["/* generated by tools/android_imports.py; do not edit */", "\t.text"]
    for index, name in enumerate(names):
        # (the table's entries are the host's 64-bit addresses)
        stub = arch.import_stub.format(name=name, offset=index * 8).split("\n")
        if base_register and not name.startswith("hostposix_"):
            if name not in pointers:
                raise SystemExit(f"{name}: no prototype in the --prototypes files")
            # (AArch64's: the only architecture with a base register,
            # tools/guest_arch.py base_register_flags)
            translate = []
            for register in pointers[name]:
                translate += [
                    f"\tcbz w{register}, 1{register}f",
                    f"\tadd x{register}, x21, w{register}, uxtw",
                    f"1{register}:",
                ]
            label = stub.index(f"{name}:") + 1
            stub[label:label] = translate
        out += stub
    out += [
        "\t.section .rodata",
        "\t.globl __host_import_names",
        "__host_import_names:",
    ]
    out += [f'\t.asciz "{name}"' for name in names]
    out += [
        "\t.p2align 2",
        "\t.globl __host_import_count",
        "__host_import_count:",
        f"\t.long {len(names)}",
        "\t.data",
        "\t.p2align 3",
        "\t.globl __host_import_table",
        "__host_import_table:",
        f"\t.zero {max(len(names), 1) * 8}",
    ]
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    if host_table:
        host_names = names
        if host_abi == "sysv":
            table = sysv_host_table(host_names, thunk_prototypes(prototype_files))
        else:
            table = ["/* generated by tools/android_imports.py; do not edit */",
                     "#include <string.h>", ""]
            table += [f"extern void {host_symbol(n)}(void);" for n in host_names]
            table += ["", "static const struct { const char *name; void *function; } imports[] =", "{"]
            table += [f'\t{{ "{n}", (void *){host_symbol(n)} }},' for n in host_names]
            table += ["};", ""]
        table += ["void *host_resolve_import(const char *name)",
                  "{",
                  "\tunsigned long index;",
                  "",
                  "\tfor (index = 0; index < sizeof(imports) / sizeof(imports[0]); index++)",
                  "\t{",
                  "\t\tif (!strcmp(imports[index].name, name))",
                  "\t\t\treturn imports[index].function;",
                  "\t}",
                  "\treturn NULL;",
                  "}"]
        with open(host_table, "w", encoding="utf-8") as f:
            f.write("\n".join(table) + "\n")


if __name__ == "__main__":
    main()
