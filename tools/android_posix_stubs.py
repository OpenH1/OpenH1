#!/usr/bin/env python3
"""Generate the Android guest's side of port/linux/src/posix.h.

The posix_*.c helpers run in the Android host (they are the platform
layer's only contact with the C library's file system and sockets). Their
interface is 32-bit clean, so the guest can call them directly, except for
errno: the host's is not the guest's. Each generated wrapper calls the host
function through an import named hostposix_<name> and copies the host's
errno into the guest's afterwards.

With --base-register, the guest's memory lies at a base in x21
(tools/guest_base_register.py): pointer arguments go to the host as host
addresses (base plus offset; NULL stays NULL).

Usage: android_posix_stubs.py [--base-register] posix.h output.c imports.list
"""

import re
import sys

# the pointer arguments that are the host's handles, not guest addresses:
# a 64-bit host's directory streams are handles from 1 to 64
# (posix_files.c's directory_handle_new), which posix_directory_open
# returns. With the base register they must reach the host as they are;
# made host addresses (base plus the handle), the host found no stream, and
# every directory listed empty (the macOS build's saved games and player
# profiles, never found again after a restart)
HANDLE_ARGUMENTS = {("posix_directory_next", "directory"), ("posix_directory_close", "directory")}


def main():
    arguments = sys.argv[1:]
    base_register = arguments[0] == "--base-register"
    if base_register:
        arguments = arguments[1:]
    header, output, imports = arguments[:3]
    text = open(header, encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    prototypes = re.findall(r"^([A-Za-z_][\w \*]*?)\b(posix_\w+)\s*\(([^;]*?)\);", text, re.M | re.S)
    out = [
        "/* generated by tools/android_posix_stubs.py from port/linux/src/posix.h; do not edit */",
        "#include <errno.h>",
        '#include "posix.h"',
        "",
        "int host_errno(void);",
        "",
    ]
    if base_register:
        out += [
            "static inline unsigned long long host_address(const void *pointer)",
            "{",
            "\tunsigned long long base;",
            "",
            '\t__asm__("mov %0, x21" : "=r"(base));',
            "\treturn pointer ? base + (unsigned int)pointer : 0;",
            "}",
            "",
        ]
    names = []
    for ret, name, params in prototypes:
        ret = " ".join(ret.split())
        params = " ".join(params.split())
        args = []
        host_params = []
        if params != "void":
            for param in params.split(","):
                m = re.search(r"(\w+)\s*$", param.strip())
                if base_register and (name, m.group(1)) in HANDLE_ARGUMENTS:
                    # (a handle the host made, not a guest address: as it
                    # came, zero-extended)
                    args.append(f"(unsigned long long)(unsigned int){m.group(1)}")
                    host_params.append("unsigned long long")
                elif base_register and "*" in param:
                    args.append(f"host_address({m.group(1)})")
                    host_params.append("unsigned long long")
                else:
                    args.append(m.group(1))
                    host_params.append(param.strip())
        host_name = "hostposix_" + name[len("posix_"):]
        names.append(host_name)
        out.append(f"{ret} {host_name}({', '.join(host_params) or 'void'});")
        out.append(f"{ret} {name}({params})")
        out.append("{")
        call = f"{host_name}({', '.join(args)})"
        if ret == "void":
            out.append(f"\t{call};")
            out.append("\terrno = host_errno();")
        else:
            out.append(f"\t{ret} host_result = {call};")
            out.append("")
            out.append("\terrno = host_errno();")
            out.append("\treturn host_result;")
        out.append("}")
        out.append("")
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    with open(imports, "w", encoding="utf-8") as f:
        f.write("\n".join(names) + "\n")


if __name__ == "__main__":
    main()
