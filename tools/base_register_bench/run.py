#!/usr/bin/env python3
"""Measures the cost of the guest's base register (tools/guest_base_register.py).

Builds the CPU-bound kernels of bench.c as the game's guest is built
(ILP32 AArch64 code from clang's arm64_32 target, converted to ELF by
tools/android_asm_convert.py and linked by ld.lld), with and without the
base register, and natively, then times each:

- on Linux arm64: the guest without the base register (in the low 4 GB, as
  the Linux and Android builds run it) and with it: the same work, the cost
  of the base register alone;
- on macOS (Apple silicon), whose processes have no low 4 GB: the guest
  with the base register, and the same C built natively (64-bit pointers),
  for reference, with the instructions and cycles each run took; and the
  guest with each instruction the rewrite adds run twice ("base2", which
  does the same work), from which the cost of those instructions follows
  (base2 - base), and so an estimate of the guest without them
  (2 x base - base2), on either system.

With --micro, also the instruction-level cost of the rewrite's patterns on
this core (micro.c).

Usage: python3 tools/base_register_bench/run.py [--repeats N] [--quick] [--micro]
Run from the repository's root; builds in build/base_register_bench.
Needs clang with the arm64_32 target (Apple's, or LLVM's), ld.lld and, for
the harness, the host's C compiler.
"""

import argparse
import json
import math
import platform
import random
import shutil
import subprocess
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
HERE = Path(__file__).resolve().parent
BUILD = ROOT / "build" / "base_register_bench"
ZLIB_DIR = ROOT / "port" / "third_party" / "zlib"
MONOCYPHER_DIR = ROOT / "port" / "third_party" / "monocypher"
ZLIB_SOURCES = ("adler32.c", "crc32.c", "inffast.c", "inflate.c", "inftrees.c", "zutil.c")

# bench.c's kernels and the scale each runs at (about a second, natively,
# on an Apple A18 Pro)
KERNELS = [("tree", 4), ("list", 24), ("sort", 12), ("inflate", 400), ("hash", 300), ("objects", 300)]

# the game's guest's code generation (tools/android_build.py, GUEST_ABI_FLAGS)
GUEST_FLAGS = [
    "--target=arm64_32-apple-watchos", "-mcpu=cortex-a53", "-O2", "-ffp-contract=off", "-fno-stack-protector",
    "-fno-unwind-tables", "-fno-asynchronous-unwind-tables", "-fno-omit-frame-pointer", "-mllvm",
    "-aarch64-neon-syntax=generic",
    # (Apple's clang on macOS: its sysroot is not the target's, which needs none)
    "-Wno-unknown-warning-option", "-Wno-incompatible-sysroot",
]
# and its base register's (tools/android_build.py, generate_guest_image)
BASE_FLAGS = ["-ffixed-x21", "-ffixed-x22", "-mllvm", "-aarch64-enable-compress-jump-tables=false"]
COMMON_FLAGS = ["-ffreestanding", "-DZ_SOLO", "-DZ_PREFIX", "-Dz_errmsg=z_port_errmsg",
                f"-I{ZLIB_DIR}", f"-I{MONOCYPHER_DIR}"]


def tool(name):
    found = shutil.which(name)
    if found:
        return found
    for directory in ("/opt/homebrew/opt/llvm/bin", "/opt/homebrew/opt/lld/bin", "/usr/lib/llvm-18/bin"):
        if (Path(directory) / name).is_file():
            return str(Path(directory) / name)
    sys.exit(f"{name} not found")


def run(command, **options):
    subprocess.run([str(part) for part in command], check=True, **options)


def write_data(path):
    """Compressible text of a fixed seed for the inflate kernel, deflated."""
    words = ["warthog", "banshee", "ghost", "plasma", "rifle", "pistol", "shotgun", "covenant", "elite", "grunt",
             "jackal", "hunter", "marine", "pelican", "halo", "ring", "control", "room", "cartographer", "flood"]
    generator = random.Random(2342)
    text = " ".join(generator.choice(words) + str(generator.randrange(100)) for _ in range(120000)).encode()
    text = text[:768 * 1024]
    deflated = zlib.compress(text, 6)
    rows = ",\n".join(", ".join(str(byte) for byte in deflated[index:index + 32])
                      for index in range(0, len(deflated), 32))
    path.write_text("/* generated by tools/base_register_bench/run.py */\n"
                    f"const unsigned char bench_deflated[] = {{\n{rows}\n}};\n"
                    f"const unsigned int bench_deflated_size = {len(deflated)};\n"
                    f"const unsigned int bench_inflated_size = {len(text)};\n")


def build_guest(clang, ld, variant, sources):
    """The guest image, with (variant "base") or without the base register."""
    directory = BUILD / variant
    directory.mkdir(parents=True, exist_ok=True)
    resource = subprocess.run([clang, "-print-resource-dir"], capture_output=True, text=True,
                              check=True).stdout.strip()
    flags = GUEST_FLAGS + COMMON_FLAGS + ["-nostdinc", "-isystem", f"{resource}/include"]
    if variant.startswith("base"):
        flags += BASE_FLAGS
    objects = []
    for source in sources:
        darwin = directory / (source.stem + ".darwin.s")
        elf = directory / (source.stem + ".s")
        obj = directory / (source.stem + ".o")
        run([clang, *flags, "-S", source, "-o", darwin])
        run([sys.executable, ROOT / "tools" / "android_asm_convert.py",
             *(["--base-register"] if variant == "base" else []), darwin, elf])
        if variant == "base2":
            sys.path.insert(0, str(ROOT / "tools"))
            from guest_base_register import rewrite
            elf.write_text("\n".join(rewrite(elf.read_text().split("\n"), double=True)[0]))
        run([clang, "--target=aarch64-linux-gnu", "-c", elf, "-o", obj])
        objects.append(obj)
    image = directory / "bench.elf"
    run([ld, "-m", "aarch64linux", "-static", "-nostdlib", "-T", HERE / "bench.ld", "-o", image, *objects])
    return image


def build_harnesses(cc, sources):
    harness = BUILD / "harness"
    run([cc, "-O2", "-o", harness, HERE / "harness.c", ROOT / "port" / "android" / "host" / "host_enter.S"])
    native = BUILD / "harness_native"
    run([cc, "-O2", "-mcpu=cortex-a53", "-ffp-contract=off", "-fno-stack-protector", "-DBENCH_NATIVE",
         *COMMON_FLAGS, "-fno-builtin", "-o", native, HERE / "harness.c",
         ROOT / "port" / "android" / "host" / "host_enter.S", *sources])
    return harness, native


def measure(command, repeats):
    output = subprocess.run([str(part) for part in command] + [str(repeats)], capture_output=True, text=True,
                            check=True).stdout.split()
    checksum, nanoseconds, instructions, cycles = (int(value) for value in output)
    return {"checksum": checksum, "ns": nanoseconds, "instructions": instructions, "cycles": cycles}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repeats", type=int, default=5)
    parser.add_argument("--quick", action="store_true", help="a tenth of the work (a check, not a measurement)")
    parser.add_argument("--micro", action="store_true", help="also the cost of each instruction pattern (micro.c)")
    arguments = parser.parse_args()
    machine = platform.machine().lower()
    linux = sys.platform.startswith("linux") and machine in ("aarch64", "arm64")
    macos = sys.platform == "darwin" and machine == "arm64"
    if not (linux or macos):
        sys.exit("runs on Linux arm64 or macOS on Apple silicon")
    clang = tool("clang")
    ld = tool("ld.lld")
    BUILD.mkdir(parents=True, exist_ok=True)
    data = BUILD / "bench_data.c"
    write_data(data)
    sources = [HERE / "bench.c", data, *(ZLIB_DIR / name for name in ZLIB_SOURCES), MONOCYPHER_DIR / "monocypher.c"]
    images = {"base": build_guest(clang, ld, "base", sources), "base2": build_guest(clang, ld, "base2", sources)}
    if linux:
        images["low"] = build_guest(clang, ld, "low", sources)
    harness, native = build_harnesses(clang, sources)

    modes = ["low", "base", "base2"] if linux else ["native", "base", "base2"]
    results = {}
    for index, (name, scale) in enumerate(KERNELS):
        if arguments.quick:
            scale = max(1, scale // 10)
        results[name] = {}
        for mode in modes:
            if mode == "native":
                command = [native, "native", index, scale]
            else:
                command = [harness, images[mode], "low" if mode == "low" else "base", index, scale]
            results[name][mode] = measure(command, arguments.repeats)
        checksums = {results[name][mode]["checksum"] for mode in modes}
        if len(checksums) != 1:
            sys.exit(f"{name}: the builds disagree: {results[name]}")

    reference = modes[0]
    print(f"{platform.platform()}; best of {arguments.repeats}; times in ms")
    print(f"{'kernel':10} {reference:>9} {'base':>9} {'base2':>9} {'base/' + reference:>12} "
          f"{'added cost':>11} {'instr. added':>13}")
    ratios, added_costs = [], []
    for name, _ in KERNELS:
        a, b, c = (results[name][mode] for mode in modes)
        ratio = b["ns"] / a["ns"]
        # the rewrite's added instructions: their time, as a part of what
        # the guest takes without them (2 base - base2)
        added = (c["ns"] - b["ns"]) / (2 * b["ns"] - c["ns"])
        instructions = ((c["instructions"] - b["instructions"]) / (2 * b["instructions"] - c["instructions"])
                        if b["instructions"] else float("nan"))
        ratios.append(ratio)
        added_costs.append(1 + added)
        print(f"{name:10} {a['ns'] / 1e6:9.1f} {b['ns'] / 1e6:9.1f} {c['ns'] / 1e6:9.1f} {ratio:12.3f} "
              f"{added:+11.1%} {instructions:+13.1%}")
    geomean = lambda values: math.exp(sum(math.log(value) for value in values) / len(values))
    print(f"{'geomean':10} {'':9} {'':9} {'':9} {geomean(ratios):12.3f} {geomean(added_costs) - 1:+11.1%}")
    (BUILD / "results.json").write_text(json.dumps(results, indent=1) + "\n")
    if arguments.micro:
        micro = BUILD / "micro"
        run([clang, "-O2", "-o", micro, HERE / "micro.c"])
        print(flush=True)
        run([micro])


if __name__ == "__main__":
    main()
