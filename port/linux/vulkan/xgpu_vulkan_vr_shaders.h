/*
XGPU_VULKAN_VR_SHADERS.H

The fixed VR passes, generated by tools/vulkan_vr_shaders.py from their
GLSL (xgpu_vulkan_vr_glsl.inc). Uniforms use descriptor set 0, binding 1;
combined image samplers use set 1, bindings 0 through texture_count - 1.
All images have their first row at the top. framebuffer_height is required
for each pass that uses fragment coordinates.

Each uniform's data is scalar 32-bit floats or integers. Arrays use their
std140 stride (16 for a scalar array); components are contiguous within an
element. The CPU may keep the GL uniform setup by looking up these offsets
and copying each element into a zeroed uniform buffer.
*/

#ifndef XGPU_VULKAN_VR_SHADERS_H
#define XGPU_VULKAN_VR_SHADERS_H

#include <stdint.h>
#include <stddef.h>

enum xgpu_vulkan_vr_program_id
{
	XGPU_VULKAN_VR_FOVEA,
	XGPU_VULKAN_VR_LIGHT,
	XGPU_VULKAN_VR_HUD,
	XGPU_VULKAN_VR_SCOPE,
	XGPU_VULKAN_VR_VISOR,
	XGPU_VULKAN_VR_RIM,
	XGPU_VULKAN_VR_FEED,
	XGPU_VULKAN_VR_COCKPIT,
	XGPU_VULKAN_VR_VIGNETTE,
	XGPU_VULKAN_VR_TINT,
	XGPU_VULKAN_VR_DEPTH,
	XGPU_VULKAN_VR_SCOPE_WINDOW,
	XGPU_VULKAN_VR_COPY,
	XGPU_VULKAN_VR_PROGRAM_COUNT
};

struct xgpu_vulkan_vr_uniform
{
	const char *name;
	unsigned int offset, components, count, stride;
	int integer;
};

struct xgpu_vulkan_vr_program
{
	const char *name;
	const uint32_t *vertex_words, *fragment_words;
	size_t vertex_bytes, fragment_bytes;
	const struct xgpu_vulkan_vr_uniform *uniforms;
	unsigned int uniform_count, uniform_size;
	const char *textures[4];
	unsigned int texture_count;
	/* 2 for the stereo passes (view mask 3), otherwise 1 */
	unsigned int views;
};

extern const struct xgpu_vulkan_vr_program xgpu_vulkan_vr_programs[XGPU_VULKAN_VR_PROGRAM_COUNT];

#endif
